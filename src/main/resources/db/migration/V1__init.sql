-- EXTENSIONS

CREATE EXTENSION IF NOT EXISTS pg_trgm;

-- TABLES

CREATE TABLE authors (
    name VARCHAR(100) NOT NULL,
    CONSTRAINT pk_authors PRIMARY KEY (name)
);

CREATE TABLE books (
    isbn VARCHAR(13) NOT NULL,
    title VARCHAR(150) NOT NULL,
    available_copies INTEGER NOT NULL,
    publication_year INTEGER,
    version BIGINT,
    CONSTRAINT pk_books PRIMARY KEY (isbn),
    CONSTRAINT chk_books_copies CHECK (available_copies >= 0),
    CONSTRAINT chk_books_year CHECK (publication_year >= 1)
);

CREATE TABLE books_authors (
    books_isbn VARCHAR(13) NOT NULL,
    authors_name VARCHAR(100) NOT NULL,
    CONSTRAINT pk_books_authors PRIMARY KEY (books_isbn, authors_name)
);

CREATE TABLE customers (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email VARCHAR(150),
    first_name VARCHAR(100) NOT NULL,
    last_name VARCHAR(100) NOT NULL,
    version BIGINT,
    CONSTRAINT uk_customers_email UNIQUE (email)
);

CREATE TABLE copies (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    book_isbn VARCHAR(13) NOT NULL,
    customer_id BIGINT,
    status VARCHAR(9) NOT NULL,
    version BIGINT,
    CONSTRAINT chk_copies_status CHECK (status IN ('AVAILABLE', 'RESERVED', 'BORROWED', 'LOST'))
);

CREATE TABLE users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(50) NOT NULL,
    password VARCHAR(100) NOT NULL,
    role VARCHAR(20) NOT NULL,
    customer_id BIGINT,
    version BIGINT,
    CONSTRAINT uk_users_username UNIQUE (username),
    CONSTRAINT uk_users_customer UNIQUE (customer_id),
    CONSTRAINT chk_users_role CHECK (role IN ('ROLE_LIBRARIAN', 'ROLE_CUSTOMER'))
);

-- INDEXES

-- Books
CREATE INDEX IF NOT EXISTS idx_books_title_pattern ON books USING gin (title gin_trgm_ops);

-- Books_Authors
CREATE INDEX IF NOT EXISTS idx_books_authors ON books_authors (books_isbn, authors_name);
CREATE INDEX IF NOT EXISTS idx_books_authors_reverse ON books_authors (authors_name, books_isbn);

-- Copies
CREATE INDEX IF NOT EXISTS idx_copies_book_status ON copies (book_isbn, status);
CREATE INDEX IF NOT EXISTS idx_copies_customer_id ON copies (customer_id);

-- Customers
CREATE INDEX IF NOT EXISTS idx_customer_name ON customers (last_name, first_name);
CREATE INDEX IF NOT EXISTS idx_customer_lastname_pattern ON customers USING gin (last_name gin_trgm_ops);

-- Users
CREATE INDEX IF NOT EXISTS idx_users_username ON users (username);

-- FOREIGN KEYS

ALTER TABLE books_authors
    ADD CONSTRAINT fk_books_authors_book FOREIGN KEY (books_isbn) REFERENCES books(isbn),
    ADD CONSTRAINT fk_books_authors_author FOREIGN KEY (authors_name) REFERENCES authors(name);

ALTER TABLE copies
    ADD CONSTRAINT fk_copies_book FOREIGN KEY (book_isbn) REFERENCES books(isbn),
    ADD CONSTRAINT fk_copies_customer FOREIGN KEY (customer_id) REFERENCES customers(id);

ALTER TABLE users
    ADD CONSTRAINT fk_users_customer FOREIGN KEY (customer_id) REFERENCES customers(id);